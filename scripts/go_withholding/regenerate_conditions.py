"""Regenerate every withholding condition on another machine, verified against the pins.

Remote GPU execution (user decision B): instead of shipping the ~4.4 GB of
condition dirs, ship the pruned data (``preprocess/go_withholding/{converted,
splits,targets}``) and ``results/go_withholding/protocol_pins.json`` and run this
one command. Generation is deterministic (design 3.3/3.4, ``withholding.py``),
so the regenerated bytes must reproduce the pinned hashes exactly.

Checks, all fatal (exit 2) before anything is written:

* the latest ``G1`` pin's hashes equal ``splits/frozen_hashes.json`` and the
  files on disk (train, validation, negative pools, test, proteins, pruned
  index; pairs too when ``converted/pairs.jsonl`` is present);
* ``target_table.json`` matches its ``.sha256`` sidecar and the latest
  ``G2-targets`` pin;
* the target-free validation set (regenerated if absent, else verified
  idempotently) has the manifest sha256 of the latest ``G2-validation`` pin;
* the latest ``G3`` pin lists exactly ``condition_ids(table)`` and
  ``n_conditions``;
* free disk >= ``make_conditions.MIN_FREE_BYTES``;
* per condition, the in-memory manifest sha256 equals ``G3["manifests"][cond]``
  BEFORE the dir is written; then ``build_condition`` writes it (or verifies an
  existing dir byte-for-byte) with every design 3.4 check.

No pin is appended: this reproduces G2-validation/G3, it does not re-run them.

Usage (from the checkout root, any machine)::

    python scripts/go_withholding/regenerate_conditions.py            # all n_conditions
    python scripts/go_withholding/regenerate_conditions.py --only all p01_k0
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import logging
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from go_ppi_domain import withholding as wh  # noqa: E402
from go_ppi_domain import withholding_constants as wc  # noqa: E402
from scripts.go_withholding import make_conditions as mc  # noqa: E402

logger = logging.getLogger("regenerate_conditions")

#: frozen_hashes / G1 key -> (dir, file); ``None`` dir -> optional file.
G1_FILES = {"train_sha256": ("splits", "train.jsonl"),
            "validation_sha256": ("splits", "validation.jsonl"),
            "negative_pools_sha256": ("splits", "negative_pools.jsonl"),
            "test_sha256": ("splits", "test.jsonl"),
            "proteins_sha256": ("converted", "proteins.jsonl"),
            "go_index_P_sha256": ("converted", "go_index_P.pkl")}
OPTIONAL_G1_FILES = {"pairs_sha256": ("converted", "pairs.jsonl")}


class RegenError(RuntimeError):
    pass


def latest_pin(gate: str) -> Dict[str, Any]:
    pins = [e for e in wc.read_pins() if e.get("gate") == gate]
    if not pins:
        raise RegenError(f"pins file {wc.rel_to_root(wc.pins_path())} has no {gate} entry")
    return pins[-1]


def verify_base(splits: Path, converted: Path) -> Dict[str, Any]:
    g1 = latest_pin("G1")
    frozen = json.loads((splits / "frozen_hashes.json").read_text(encoding="utf-8"))
    dirs = {"splits": splits, "converted": converted}
    checked = []
    for key, (where, name) in {**G1_FILES, **OPTIONAL_G1_FILES}.items():
        path = dirs[where] / name
        if key in OPTIONAL_G1_FILES and not path.exists():
            continue
        if frozen.get(key) != g1.get(key):
            raise RegenError(f"frozen_hashes[{key}] != G1 pin")
        got = wc.sha256_file(path)
        if got != g1.get(key):
            raise RegenError(f"{where}/{name} sha256 {got} != G1 pin {g1.get(key)}")
        checked.append(f"{where}/{name}")
    return {"frozen": frozen, "checked": checked}


def verify_table(table_path: Path) -> Dict[str, Any]:
    t = mc.load_table(table_path)
    pin = latest_pin("G2-targets")
    if t["sha256"] != pin.get("target_table_sha256"):
        raise RegenError(f"target_table.json sha256 {t['sha256']} != G2-targets pin "
                         f"{pin.get('target_table_sha256')}")
    return t


def regenerate(table_path: Path, splits: Path, converted: Path, targetfree: Path,
               out: Path, only: Optional[List[str]] = None) -> Dict[str, Any]:
    from go_ppi_domain.go_ontology import GoIndex

    base_check = verify_base(splits, converted)
    t = verify_table(table_path)
    table = t["table"]
    g3 = latest_pin("G3")
    cond_ids = wh.condition_ids(table)
    if (len(cond_ids) != int(table["n_conditions"]) or int(g3.get("n_conditions", -1))
            != int(table["n_conditions"]) or sorted(g3.get("manifests", {})) != sorted(cond_ids)):
        raise RegenError("G3 pin does not list exactly the table's n_conditions conditions")
    wanted = cond_ids if not only else list(only)
    unknown = sorted(set(wanted) - set(cond_ids))
    if unknown:
        raise RegenError(f"unknown condition ids {unknown[:5]}")
    free = mc._free_bytes(out)
    if free < mc.MIN_FREE_BYTES:
        raise RegenError(f"only {free / 1e9:.2f} GB free (< {mc.MIN_FREE_BYTES / 1e9:.0f} GB)")
    wc.assert_writable_target(out)
    wc.assert_writable_target(targetfree)

    base = wh.load_base(splits, converted)
    vpin = latest_pin("G2-validation")
    # Absent -> built in a sibling staging dir and moved into place only if it
    # reproduces the pin; present -> verified byte-for-byte (idempotent rule).
    fresh = not (targetfree.exists() and any(targetfree.iterdir()))
    target = targetfree.with_name(targetfree.name + ".regen_tmp") if fresh else targetfree
    if fresh and target.exists():
        shutil.rmtree(target)
    vman = wh.build_targetfree_validation(table, splits, target, base=base,
                                          table_sha=t["sha256"])
    if vman["manifest_sha256"] != vpin.get("manifest_sha256"):
        if fresh:
            shutil.rmtree(target, ignore_errors=True)
        raise RegenError(f"target-free validation manifest {vman['manifest_sha256']} != "
                         f"G2-validation pin {vpin.get('manifest_sha256')}")
    if fresh:
        if targetfree.exists():
            targetfree.rmdir()
        target.rename(targetfree)
    val_pool_bytes = (targetfree / "negative_pools_validation.jsonl").read_bytes()
    val_pool_sha = wc.sha256_file(targetfree / "negative_pools_validation.jsonl")
    index = GoIndex.load(converted / "go_index_P.pkl")
    status: Dict[str, str] = {}
    for cid in wanted:
        files, _ = wh._condition_files(table, cid, base, val_pool_bytes, t["sha256"],
                                       val_pool_sha)
        got = hashlib.sha256(files[wh.MANIFEST]).hexdigest()
        if got != g3["manifests"][cid]:
            raise RegenError(f"{cid}: regenerated manifest sha256 {got} != G3 pin "
                             f"{g3['manifests'][cid]} (nothing written for it)")
        m = wh.build_condition(table, cid, splits, targetfree, out / cid, base=base,
                               table_sha=t["sha256"], index=index)
        if m["manifest_sha256"] != g3["manifests"][cid]:
            raise RegenError(f"{cid}: written manifest differs from the G3 pin")
        status[cid] = m["status"]
        logger.info("%s: %s", cid, m["status"])
    if not only:
        written = sorted(p.name for p in out.iterdir()
                         if p.is_dir() and (p / wh.MANIFEST).is_file())
        if written != sorted(cond_ids):
            raise RegenError(f"{len(written)} condition dirs present != n_conditions "
                             f"{table['n_conditions']}")
    return {"n_conditions": len(status), "verified_base": base_check["checked"],
            "target_table_sha256": t["sha256"], "validation": vman["status"],
            "written": sum(v == "written" for v in status.values()),
            "unchanged": sum(v == "unchanged" for v in status.values())}


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--target-table", type=Path, default=None)
    ap.add_argument("--base-splits", type=Path, default=None)
    ap.add_argument("--converted", type=Path, default=None)
    ap.add_argument("--targetfree-validation", type=Path, default=None)
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument("--only", nargs="+", default=None, metavar="COND_ID",
                    help="regenerate only these condition ids (still pin-verified)")
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    t0 = time.time()
    try:
        summary = regenerate(
            Path(args.target_table or (Path(wc.TARGETS) / "target_table.json")),
            Path(args.base_splits or wc.SPLITS), Path(args.converted or wc.CONVERTED),
            Path(args.targetfree_validation or wc.VALIDATION_TF),
            Path(args.out or wc.CONDITIONS), args.only)
    except Exception as exc:  # noqa: BLE001 - every mismatch is fatal
        logger.error("regenerate_conditions failed: %s: %s", type(exc).__name__, exc)
        return 2
    summary["wall_seconds"] = round(time.time() - t0, 1)
    print(json.dumps(summary, indent=1, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
